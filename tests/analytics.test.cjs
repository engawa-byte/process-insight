const assert = require('node:assert/strict');
const A = require('../analytics.js');
const cols = ['日付','担当者','処理件数','作業時間（分）'];
const row = (staff, count, minutes) => ({'日付':'2026-10-01','担当者':staff,'処理件数':String(count),'作業時間（分）':String(minutes)});
const rows = A.validateRecords([row('田中',1,10),row('田中',9,9),row('佐藤',5,20)],cols);
const stats = A.summarize(rows);
assert.equal(stats.totalCount,15);
assert.equal(stats.totalMinutes,39);
assert.equal(stats.average,2.6); // 担当者別単純平均にはならない
assert.equal(stats.people[0].staff,'田中');
assert.equal(stats.people[0].average,1.9);
assert.equal(stats.people[0].share,10/15*100);
assert.equal(stats.recordCount,3);
assert.equal(A.summarize([rows[2]]).average,4);
assert.equal(A.summarize([]).average,null);
assert.equal(A.summarize(A.validateRecords([row('無作業',0,0)],cols)).average,null);
assert.equal(A.validIsoDate('2026-02-29'),false);
assert.equal(A.validIsoDate('2024-02-29'),true);
assert.throws(() => A.validateRecords([row('田中','-1',2)],cols),/整数/);
assert.throws(() => A.validateRecords([row('田中','1.3',2)],cols),/整数/);
assert.throws(() => A.validateRecords([row('田中',1,'NaN')],cols),/数値/);
assert.throws(() => A.validateRecords([row('田中',1,'-2')],cols),/数値/);
assert.throws(() => A.validateRecords([{'日付':'2026-02-29','担当者':'田中','処理件数':'1','作業時間（分）':'2'}],cols),/日付/);
const hugeMinutes = `1${'0'.repeat(308)}`;
assert.throws(() => A.validateRecords([row('田中',1,hugeMinutes),row('田中',1,hugeMinutes)],cols),/安全な数値範囲/);
assert.throws(() => A.validateRecords([row('田中',Number.MAX_SAFE_INTEGER,1),row('田中',1,1)],cols),/安全な数値範囲/);
assert.throws(() => A.validateRecords([{'日付':'2026-10-01','担当者':'','処理件数':'10','作業時間（分）':'3'}],cols),/担当者/);
assert.throws(() => A.validateRecords([row('田中',2,4)],cols.slice(0,3)),/必須列/);
assert.throws(() => A.validateRecords([row('田中',2,4)],cols.concat('担当者')), /重複/);
const escaped = '日付,担当者,処理件数,作業時間（分）\r\n2026-10-01,"A, ""B""",2,6\r\n2026-10-02,"複数\n行",3,8\r\n';
const csv = A.parseCsvFallback(escaped);
assert.equal(csv.errors.length,0);
assert.equal(csv.data[0]['担当者'],'A, "B"');
assert.equal(csv.data[1]['担当者'],'複数\n行');
assert.equal(A.validateRecords(csv.data,csv.meta.fields).length,2);
assert.match(A.safeCsv([{'担当者':'=HYPERLINK("x")','処理件数':1}],['担当者','処理件数']),/^担当者,処理件数\r\n"'=HYPERLINK/);
assert.ok(A.parseCsvFallback('a,b\n"bad,2').errors.length > 0);
console.log('PASS: 28 analytics/CSV validation assertions');
